/**
 * Grouped shelf stacks by tier and bay for 3D physical layout in JapaneseRoomService
 */
export function getShelfTierStacks(): Array<{
  tier: number
  bay: 'left' | 'right'
  books: ShelfBookConfig[]
}> {
  const tiers = [4, 3, 2, 1]
  const bays: Array<'left' | 'right'> = ['left', 'right']
  const stacks: Array<{ tier: number; bay: 'left' | 'right'; books: ShelfBookConfig[] }> = []

  for (const tier of tiers) {
    for (const bay of bays) {
      const books = SHELF_BOOKS_CONFIG.filter((b) => b.tier === tier && b.bay === bay)
      if (books.length > 0) {
        stacks.push({ tier, bay, books })
      }
    }
  }
  return stacks
}

export function getShelfBookById(id: string): ShelfBookConfig | undefined {
  return SHELF_BOOKS_CONFIG.find((b) => b.id === id)
}

export function getShelfBooksByClass(classLevel: number): ShelfBookConfig[] {
  return SHELF_BOOKS_CONFIG.filter((b) => b.classLevel === classLevel)
}
